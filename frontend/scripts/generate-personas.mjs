// собирает статический public/personas.json из frontend/data/compendium.tsv.
// запускается на pre-сборке, чтобы фронтенд не зависел от рантайм-бэкенда:
// TSV остаётся единственным источником правды, а на прод уезжает готовый JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const TSV_PATH = resolve(here, "../data/compendium.tsv");
const OUT_PATH = resolve(here, "../public/personas.json");
const META_PATH = resolve(here, "../src/generated-meta.ts");
const SITEMAP_PATH = resolve(here, "../public/sitemap.xml");
const SITE = "https://persona-compendium-1zox.onrender.com";

const INT_FIELDS = new Set([
  "id",
  "level",
  "strength",
  "magic",
  "endurance",
  "agility",
  "luck",
  "dlc",
]);
const ARRAY_FIELDS = new Set([
  "weak",
  "resists",
  "reflects",
  "absorbs",
  "nullifies",
]);

const raw = readFileSync(TSV_PATH, "utf8");
const lines = raw.split(/\r?\n/).filter((line) => line.length > 0);
const headers = lines[0].split("\t");

const personas = lines.slice(1).map((line) => {
  const cells = line.split("\t");
  if (cells.length !== headers.length) {
    throw new Error(
      `row has ${cells.length} cells, expected ${headers.length}: ${line.slice(0, 40)}`,
    );
  }
  const row = {};
  headers.forEach((header, index) => {
    const value = (cells[index] ?? "").trim();
    if (INT_FIELDS.has(header)) {
      // пустая/нечисловая ячейка = дрейф данных: падаем, а не молча пишем 0
      if (value === "" || !Number.isInteger(Number(value))) {
        throw new Error(
          `row id=${cells[0]} has non-integer "${header}": "${value}"`,
        );
      }
      row[header] = Number(value);
    } else if (ARRAY_FIELDS.has(header)) {
      row[header] = value
        ? value.split(",").map((item) => item.trim()).filter(Boolean)
        : [];
    } else {
      row[header] = value;
    }
  });
  if (!row.query) {
    throw new Error(`row with id=${row.id} has no query field`);
  }
  // query уходит в путь ФС (dist/persona/<query>) и в URL: жёстко ограничиваем
  // безопасным набором, чтобы исключить ../ и path-traversal при пре-рендере
  if (!/^[a-z0-9-]+$/.test(row.query)) {
    throw new Error(`row with id=${row.id} has unsafe query: ${row.query}`);
  }
  // локально зеркалированный арт лежит в public/personas/<query>.webp
  row.image = `/personas/${row.query}.webp`;
  return row;
});

// целостность данных проверяется на этапе сборки (замена старой backend/CI-проверки)
const seen = new Set();
for (const persona of personas) {
  if (seen.has(persona.query)) {
    throw new Error(`duplicate query: ${persona.query}`);
  }
  seen.add(persona.query);
}
if (personas.length < 200) {
  throw new Error(`unexpectedly few personas: ${personas.length}`);
}

personas.sort((a, b) => a.id - b.id);
writeFileSync(OUT_PATH, JSON.stringify(personas));

// счётчики выводятся из TSV, чтобы pre-load плейсхолдеры в UI не разошлись с
// данными (см. src/generated-meta.ts, потребители - api.ts и Hero.tsx)
const arcanaCount = new Set(personas.map((row) => row.arcana)).size;
const meta = `// GENERATED by scripts/generate-personas.mjs - do not edit by hand.
// Counts derived from data/compendium.tsv so they cannot drift from the data.
export const PERSONA_COUNT = ${personas.length};
export const ARCANA_COUNT = ${arcanaCount};
`;
writeFileSync(META_PATH, meta);

// sitemap собирается из тех же данных: главная, индекс аркан, страницы аркан и
// персон - все с хвостовым слэшем (так их отдаёт Render, см. prerender-meta.mjs)
const arcanaSlugs = [...new Set(personas.map((row) => row.arcana))].map((name) =>
  name.toLowerCase(),
);
const urls = [
  `${SITE}/`,
  `${SITE}/skills/`,
  `${SITE}/skills/guide/`,
  `${SITE}/bosses/`,
  `${SITE}/requests/`,
  `${SITE}/arcana/`,
  ...arcanaSlugs.map((slug) => `${SITE}/arcana/${slug}/`),
  ...personas.map((row) => `${SITE}/persona/${row.query}/`),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((url) => `  <url>\n    <loc>${url}</loc>\n  </url>`).join("\n")}
</urlset>
`;
writeFileSync(SITEMAP_PATH, sitemap);

console.log(
  `generated ${personas.length} personas (${arcanaCount} arcana) -> public/personas.json + src/generated-meta.ts + public/sitemap.xml (${urls.length} urls)`,
);
